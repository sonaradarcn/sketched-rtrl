class Tracker:
    """One passive estimator plus its per-log accumulators."""

    def __init__(self, name, algo, rng, has_cert):
        self.name = name
        self.algo = algo
        self.rng = rng                    # RngSlot | _Null
        self.has_cert = has_cert
        self.has_dense = hasattr(algo, "residual_dense")
        self.cert = CertCounters(has_shadow=self.has_dense) if has_cert else None
        self.clear()

    def clear(self):
        self.acc = {k: [] for k in ("grad_cos", "rel_err", "e_t", "trueE", "rho_g",
                                    "rho_g_inf", "rho_g_lt1", "ghat_norm", "bound",
                                    "tight")}

    def flush(self):
        rec = {}
        for k, v in self.acc.items():
            m = _nanmean(v)
            if m is not None:
                rec[k] = m
        rec["n_obs"] = len(self.acc["grad_cos"])
        self.clear()
        return rec


def build_trackers(names, cell, batch, device, seed_base, drv_kw, rng_isolate):
    out = []
    for i, name in enumerate(names):
        # make_algo forwards svd_driver only to the SK-RTRL family and drops it for the
        # stochastic/local baselines, so passing it unconditionally is safe.
        algo = make_algo(name, cell, batch, **drv_kw)
        rng = (RngSlot(device, seed_base + 17 * i)
               if (rng_isolate and name in STOCHASTIC) else _Null())
        out.append(Tracker(name, algo, rng, has_cert=hasattr(algo, "e")))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--task", required=True, choices=list(TASKS))
    ap.add_argument("--n", type=int, default=64)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--steps", type=int, default=20000)
    ap.add_argument("--batch", type=int, default=8)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--log_every", type=int, default=250)
    ap.add_argument("--trackers", default=DEFAULT_TRACKERS,
                    help="comma list; default: " + DEFAULT_TRACKERS)
    ap.add_argument("--svd_driver", default="auto",
                    help='"" = leave the installed default; gesvd = kernel of record; '
                         'auto = default cuSOLVER driver first (same fallback chain)')
    ap.add_argument("--outdir", default="results/r2/e4b")
    ap.add_argument("--tag", default="")
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--clip", type=float, default=0.0)
    # time-series protocol, passed through exactly like run_m3.py / run_e1_spectrum.py
    ap.add_argument("--horizon", type=int, default=1)
    ap.add_argument("--causal", type=int, default=0)
    ap.add_argument("--washout", type=int, default=200)
    # D2 counters
    ap.add_argument("--cert_warmup", type=int, default=200)
    ap.add_argument("--cert_min_age", type=int, default=1)
    ap.add_argument("--cert_every", type=int, default=1)
    ap.add_argument("--tail_frac", type=float, default=0.2,
                    help="fraction of trailing log points averaged into tail_summary")
    ap.add_argument("--rng_isolate", type=int, default=1,
                    help="give each stochastic tracker its own RNG stream")
    ap.add_argument("--tracker_seed_base", type=int, default=-1,
                    help="-1 -> 1000 * seed")
    args = ap.parse_args()

    os.makedirs(args.outdir, exist_ok=True)
    tag = f"_{args.tag}" if args.tag else ""
    out = f"{args.outdir}/{args.task}_n{args.n}_s{args.seed}{tag}.json"
    if os.path.exists(out):
        print("exists, skip:", out)
        return

    names = [s.strip() for s in args.trackers.split(",") if s.strip()]
    seed_base = args.seed * 1000 if args.tracker_seed_base < 0 else args.tracker_seed_base

    # svd_driver is threaded through only if the installed skrtrl supports it (another
    # agent owns algos.py/train.py; probe instead of assuming).
    drv_kw, drv_ok = {}, False
    if args.svd_driver:
        drv_ok = ("svd_driver" in inspect.signature(SKRTRL.__init__).parameters)
        if drv_ok:
            drv_kw = {"svd_driver": args.svd_driver}
        else:
            print(f"note: installed skrtrl has no svd_driver argument; --svd_driver="
                  f"{args.svd_driver} ignored")
    learner_kw = {}
    if drv_kw and "svd_driver" in inspect.signature(OnlineLearner.__init__).parameters:
        learner_kw = dict(drv_kw)

    _svd_stats_reset()
    if args.task in TS_TASKS:
        task = TASKS[args.task](args.batch, args.device, seed=args.seed,
                                horizon=args.horizon, causal=bool(args.causal),
                                washout=args.washout)
        period = args.washout
    else:
        task = TASKS[args.task](args.batch, args.device, seed=args.seed)
        period = int(getattr(task, "T", 0) or 0)

    # exact-RTRL trainer: the single shared trajectory
    learner = OnlineLearner(task, args.n, "exact", lr=args.lr, device=args.device,
                            seed=args.seed, spectral_clip=args.clip, **learner_kw)
    cell = learner.cell
    trackers = build_trackers(names, cell, task.B, args.device, seed_base, drv_kw,
                              bool(args.rng_isolate))
    n, p = cell.n, cell.p

    log = {
        "args": vars(args),
        "meta": {
            "P": n * p, "p": p, "n_in": task.n_in, "n_out": task.n_out,
            "reset_period": period, "train_algo": "exact",
            "trackers": names,
            "tracker_seed_base": seed_base,
            "svd_driver_applied": args.svd_driver if drv_ok else None,
            "protocol": "common trajectory: exact RTRL trains; all estimators are "
                        "passive trackers fed the same (A_t, imm_t, delta_t) and the "
                        "same lane resets; no tracker updates any parameter",
            "tbptt": "not applicable -- TBPTT is not an online per-step estimator "
                     "(one windowed autograd gradient at window end), so no per-step "
                     "ghat_t exists on a common trajectory; see D4 for its task metric",
            "stochastic_trackers": sorted(set(names) & STOCHASTIC),
        },
        "records": [], "curve": [],
    }

    age = torch.zeros(task.B, dtype=torch.long, device=args.device)
    age_min = 0                 # scalar mirror of age.min(), kept host-side (no sync)
    metrics = []
    if args.device == "cuda":
        torch.cuda.reset_peak_memory_stats()
    t0 = time.time()
    n_labelled = 0
    for step in range(args.steps):
        x, y, new_ep = task.step()
        learner._reset_lanes(new_ep)                     # learner.h + exact J
        if new_ep.any():
            for tr in trackers:
                reset_tracker_lanes(tr.algo, new_ep)
            age[new_ep] = 0
            age_min = 0
        h_prev = learner.h.detach()
        h = cell(x, h_prev)
        A, imm = cell.jac_pieces(x, h_prev, h)
        learner.algo.step_state(A, imm)                  # exact J_t
        for tr in trackers:
            with tr.rng:
                tr.algo.step_state(A, imm)               # identical (A_t, imm_t)
        age += 1
        age_min += 1
        learner.h = h.detach()

        if y is not None:
            h_leaf = learner.h.requires_grad_(True)
            outp = learner.readout(h_leaf)
            loss, metric = learner.loss_fn(outp, y)
            learner.opt.zero_grad(set_to_none=True)
            loss.backward()
            delta = h_leaf.grad.detach()
            g_true = learner.algo.grad_rows(delta)       # exact online gradient
            n_labelled += 1

            measure = (step >= args.cert_warmup and age_min >= args.cert_min_age
                       and (n_labelled - 1) % args.cert_every == 0)
            if measure:
                with torch.no_grad():
                    dn_lane = delta.norm(dim=1)                       # (B,)
                    g_flat = g_true.flatten()
                    g_norm = float(g_true.norm())
                    # scale of the Lemma-1 test: ||J_t||_F averaged over lanes
                    j_scale = float(learner.algo.J.flatten(1).norm(dim=1).mean())
                    for tr in trackers:
                        ghat = tr.algo.grad_rows(delta)
                        c = cos(ghat.flatten(), g_flat)
                        gerr = float((g_true - ghat).norm())
                        gh_norm = float(ghat.norm())
                        tr.acc["grad_cos"].append(c)
                        tr.acc["rel_err"].append(gerr / g_norm if g_norm > EPS else float("nan"))
                        tr.acc["ghat_norm"].append(gh_norm)
                        if tr.has_cert:
                            e_lane = tr.algo.e
                            bound = float((dn_lane * e_lane).mean())
                            e_mean = float(e_lane.mean())
                            trueE = None
                            if tr.has_dense:
                                E = learner.algo.J - tr.algo.residual_dense()
                                trueE = float(E.flatten(1).norm(dim=1).mean())
                            tr.acc["e_t"].append(e_mean)
                            tr.acc["bound"].append(bound)
                            if trueE is not None:
                                tr.acc["trueE"].append(trueE)
                                if trueE > 1e-12:
                                    tr.acc["tight"].append(e_mean / trueE)
                            rho = bound / gh_norm if gh_norm > EPS else float("inf")
                            tr.acc["rho_g"].append(rho)
                            tr.acc["rho_g_inf"].append(0.0 if math.isfinite(rho) else 1.0)
                            tr.acc["rho_g_lt1"].append(1.0 if rho < 1.0 else 0.0)
                            tr.cert.update(bound, gh_norm, gerr, e_mean, trueE,
                                           g_scale=max(g_norm, gh_norm),
                                           e_scale=j_scale)

            # the trainer's own update (exact RTRL) -- trackers never touch it
            cell.apply_flat_grad(g_true)
            learner.opt.step()
            cell.clip_spectral()
            learner.h = learner.h.detach()
            metrics.append(metric)

        if step % args.log_every == 0 and metrics:
            m = sum(metrics[-200:]) / len(metrics[-200:])
            rec = {"step": step, "metric": m,
                   "age_mean": age.float().mean().item(),
                   "J_norm": learner.algo.J.flatten(1).norm(dim=1).mean().item(),
                   "trk": {tr.name: tr.flush() for tr in trackers}}
            log["records"].append(rec)
            log["curve"].append({"step": step, "metric": m})
            if step % (args.log_every * 8) == 0:
                cs = " ".join(f"{k}={v.get('grad_cos', float('nan')):.3f}"
                              for k, v in rec["trk"].items())
                print(f"[{args.task}/n{args.n}/s{args.seed}] step {step} "
                      f"metric {m:.4f} | {cs}", flush=True)
        elif step % args.log_every == 0:
            for tr in trackers:
                tr.clear()

    log["wall_s"] = time.time() - t0
    log["ms_per_step"] = 1000.0 * log["wall_s"] / max(args.steps, 1)
    if args.device == "cuda":
        log["peak_MB"] = torch.cuda.max_memory_allocated() / 2 ** 20
    log["cert"] = {tr.name: tr.cert.summary() for tr in trackers if tr.cert is not None}
    log["svd_stats"] = dict(SVD_STATS)

    # trailing-window summary (per-seed aggregation over seeds is done in post-processing)
    recs = log["records"]
    k = max(1, int(round(len(recs) * args.tail_frac)))
    tailr = recs[-k:]
    log["tail_summary"] = {"n_log_points": k, "from_step": tailr[0]["step"] if tailr else None}
    for name in names:
        vals = {}
        for key in ("grad_cos", "rel_err", "e_t", "trueE", "rho_g",
                    "rho_g_inf", "rho_g_lt1", "tight"):
            v = _nanmean([r["trk"].get(name, {}).get(key) for r in tailr])
            if v is not None:
                vals[key] = v
        log["tail_summary"][name] = vals

    with open(out, "w") as f:
        json.dump(_sanitize(log), f, indent=1)
    print("saved", out, f"({log['wall_s']:.0f}s, {log['ms_per_step']:.1f} ms/step, "
          f"{log.get('peak_MB', 0):.0f}MB, {len(recs)} log points)")
    for name in names:
        v = log["tail_summary"].get(name, {})
        print(f"  {name:<12} tail grad_cos {v.get('grad_cos', float('nan')):.4f}  "
              f"rel_err {v.get('rel_err', float('nan')):.4f}"
              + (f"  rho_g {v['rho_g']:.3g}" if v.get("rho_g") is not None else "")
              + (f"  rho_g<1 {v['rho_g_lt1']:.3f} inf {v['rho_g_inf']:.3f}"
                 if "rho_g_lt1" in v else ""))


