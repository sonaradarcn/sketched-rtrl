    s.add_argument("--no-restrict", action="store_true",
                   help="stage 2: do not restrict candidates to the stage-1 top-2")
    s.add_argument("--tasks", default="", help="comma-separated subset")
    s.add_argument("--algos", default="", help="comma-separated subset")
