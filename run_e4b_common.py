"""E4b / D4b (R2, reviewer "astra" on D4): COMMON-TRAJECTORY estimator comparison.

Why this run exists
-------------------
In D4 every estimator trains its own network, so its gradient cosine against its own
exact shadow is measured on its *own* trajectory.  Two effects are then confounded:
(a) how accurate the estimator is, and (b) where its own training took the network.
The reviewer asked for the two to be separated.  Here they are: ONE trajectory is
generated by exact RTRL, and every estimator is attached to it as a **passive tracker**
that receives exactly the same (A_t, imm_t, delta_t) and exactly the same lane resets
and never contributes to a parameter update.  Any difference in grad_cos is then a
property of the estimator alone.

Protocol (identical trajectory conventions to run_e1_spectrum.py)
-----------------------------------------------------------------
* trainer         : OnlineLearner(..., "exact") -- exact RTRL updates W, U, b and the
                    readout; the "independent reference trajectory" convention of D1.
* passive trackers: SK-RTRL r in {4, 16, 32}, SnAp-1, UORO, KF-RTRL, RFLO, each built on
                    the SAME cell object, so every tracker sees the post-update W of the
                    single shared trajectory.  step_state() is called with the trainer's
                    (A_t, imm_t); lane resets are applied to every tracker in the same
                    step as the trainer's (see `reset_tracker_lanes`).
* TBPTT is **not applicable**: it is not an online estimator with a per-step state, it
                    produces one windowed autograd gradient at window end, so there is no
                    per-step ghat_t to compare against g_t.  Recorded in meta as such.

Per-step instrumentation (labelled steps only -- delta_t exists only where the task
emits a target), stride `--cert_every`:
    per tracker   grad_cos(g, ghat), rel_err = ||g - ghat||_F / ||g||_F
    SK-RTRL/SnAp-1 additionally
                  e_t (certificate), ||E_t||_F = ||J_t - (S + L R^T)||_F,
                  bound_t = mean_b ||delta_b||_2 * e_b   (batch-consistent Theorem 1),
                  rho^g_t = bound_t / ||ghat_t||_F, direction-certifiable iff rho^g < 1
and the D2 online counters accumulated after `--cert_warmup`:
    n_steps, n_rel_lt1, n_rel_lt05, n_tight_le10, n_no_signal (+ the Theorem-1 /
    Lemma-1 violation counters, which must stay at 0).

Randomness: UORO and KF-RTRL draw Rademacher noise from the *global* torch RNG.  With
`--rng_isolate 1` (default) each stochastic tracker gets its own RNG stream, seeded from
`--tracker_seed_base` (default 1000 * seed), swapped in around its step_state.  So the
trackers are mutually independent and, importantly, the trajectory and every other
tracker are unchanged by which trackers are enabled (`--trackers` subsets stay
comparable).

Output: <outdir>/<task>_n<n>_s<seed>[_<tag>].json   (exists-skip)
  args, meta, curve (task metric), records (one entry per log point, per-tracker series),
  tail_summary (mean over the last `--tail_frac` of log points), cert (per tracker),
  wall_s, peak_MB, svd_stats.
"""
import argparse, inspect, json, math, os, time
import torch

from skrtrl.tasks import TASKS
from skrtrl.train import OnlineLearner, make_algo
from skrtrl.algos import SKRTRL, SVD_STATS, _svd_stats_reset

TS_TASKS = {"henon", "mackeyglass", "lorenz", "sunspot", "laser"}
DEFAULT_TRACKERS = "skrtrl-r4,skrtrl-r16,skrtrl-r32,snap1,uoro,kfrtrl,rflo"
STOCHASTIC = {"uoro", "kfrtrl"}          # draw from the global torch RNG every step
EPS = 1e-12


