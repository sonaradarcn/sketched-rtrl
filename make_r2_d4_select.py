def rel(path):
    """Resolve a possibly relative path against code/ (the queue's working directory)."""
    return path if os.path.isabs(path) else os.path.normpath(os.path.join(HERE, path))


# ---------------------------------------------------------------- LR ladder (1-3 decades)
def _build_ladder():
    return sorted(m * (10.0 ** e) for e in range(-7, 0) for m in (1.0, 3.0))


LADDER = _build_ladder()
LADDER_TAGS = [mj.lr_tag(x) for x in LADDER]
_TAG2IDX = {t: i for i, t in enumerate(LADDER_TAGS)}
if len(_TAG2IDX) != len(LADDER_TAGS):
    raise SystemExit("lr_tag() is not injective on the 1-3 ladder")

_base_idx = [_TAG2IDX.get(mj.lr_tag(l)) for l in BASE_LRS]
if any(i is None for i in _base_idx):
    raise SystemExit("base LR grid %s is not on the 1-3 ladder; extend _build_ladder()" % BASE_LRS)
I_LO, I_HI = min(_base_idx), max(_base_idx)
if sorted(_base_idx) != list(range(I_LO, I_HI + 1)):
    print("[warn] base LR grid is not contiguous on the 1-3 ladder; boundary levels are "
          "measured from its extremes only", file=sys.stderr)


def lr_of_tag(tag):
    i = _TAG2IDX.get(tag)
    return None if i is None else LADDER[i]


def extend_level(tag):
    """0 inside the base grid, k>0 for the k-th rung outside it, None if off-ladder."""
    i = _TAG2IDX.get(tag)
    if i is None:
        return None
    if I_LO <= i <= I_HI:
        return 0
    return I_LO - i if i < I_LO else i - I_HI


def neighbour_tag(tag, direction):
    i = _TAG2IDX.get(tag)
    if i is None:
        return None
    j = i + (1 if direction > 0 else -1)
    return LADDER_TAGS[j] if 0 <= j < len(LADDER_TAGS) else None


# ---------------------------------------------------------------- tag / path conventions
def _detect_window_flag():
    """Which run_m3.py flag carries the TBPTT window.

    Package A's A10 item adds `--tbptt_window`; until it lands `--tbptt_k` *is* the
    window (run_m3.py: `if win_len >= args.tbptt_k`), so the supplements do not depend
    on A10 -- we simply name the flag that exists in the runner we can see.
    """
    try:
        src = open(os.path.join(HERE, "run_m3.py"), encoding="utf-8", errors="replace").read()
    except OSError:
        return "tbptt_k", None
    flag = "tbptt_window" if re.search(r"--tbptt_window", src) else "tbptt_k"
    m = re.search(r'"--tbptt_k"[^)]*?default=(\d+)', src)
    return flag, (int(m.group(1)) if m else None)


WINDOW_FLAG, _detected_default = _detect_window_flag()
if _detected_default is not None and _detected_default != TBPTT_DEFAULT_WINDOW:
    print("[warn] run_m3.py --tbptt_k default is %s, this script assumed %s; bare TBPTT "
          "tags now mean window %s"
          % (_detected_default, TBPTT_DEFAULT_WINDOW, _detected_default), file=sys.stderr)
    TBPTT_DEFAULT_WINDOW = _detected_default


def is_tbptt(algo):
    return bool(algo) and (algo in TBPTT_ALGOS or algo.startswith("tbptt"))


def tag_for(algo, lrtag, window):
    """Filename tag.

    Bare `lrNe-NN` whenever the window is the run_m3 default, so the tags of the stage-1
    grid already emitted by make_r2_jobs.py are reproduced byte-for-byte; `lrNe-NN_w<W>`
    for any other TBPTT window.  If package A later grows its own `tbptt_tag(lr, w)`
    helper we defer to it.
    """
    hook = getattr(mj, "tbptt_tag", None)
    if is_tbptt(algo) and window is not None and callable(hook):
        return hook(lr_of_tag(lrtag), window)
    if is_tbptt(algo) and window is not None and int(window) != TBPTT_DEFAULT_WINDOW:
        return "%s_w%d" % (lrtag, int(window))
    return lrtag


def out_path(outdir, task, algo, seed, tag):
    """Same expression as make_r2_jobs.m3_job's `# out=` annotation."""
    return "%s/%s_%s_s%s_%s.json" % (outdir, task, algo, seed, tag)


def job_line(task, algo, seed, lrtag, window, steps, outdir):
    lr = lr_of_tag(lrtag)
    if lr is None:
        raise SystemExit("cannot map tag %r back to a learning rate" % lrtag)
    extra = ""
    if is_tbptt(algo) and window is not None:
        extra = "--%s %d" % (WINDOW_FLAG, int(window))
    return mj.m3_job(task, algo, seed, lr, steps, outdir,
                     tag_for(algo, lrtag, window), svd_driver="auto", shadow=1, extra=extra)


def expected_windows(algo):
    return list(TBPTT_WINDOWS) if is_tbptt(algo) else [None]


# ---------------------------------------------------------------- metric direction check
def loss_types_from_source(path):
    """Map task name -> loss_type by parsing skrtrl/tasks.py (no torch import)."""
    tree = ast.parse(open(path, encoding="utf-8").read())
    lt, bases, factories = {}, {}, {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            bases[node.name] = [b.id for b in node.bases if isinstance(b, ast.Name)]
            for st in node.body:
                if (isinstance(st, ast.Assign) and len(st.targets) == 1
                        and isinstance(st.targets[0], ast.Name)
                        and st.targets[0].id == "loss_type"
                        and isinstance(st.value, ast.Constant)):
                    lt[node.name] = st.value.value
        elif isinstance(node, ast.FunctionDef):
            for st in ast.walk(node):
                if (isinstance(st, ast.Return) and isinstance(st.value, ast.Call)
                        and isinstance(st.value.func, ast.Name)):
                    factories[node.name] = st.value.func.id

    def resolve(name, depth=0):
        if depth > 10:
            return None
        if name in factories:
            name = factories[name]
        if name in lt:
            return lt[name]
        for b in bases.get(name, []):
            r = resolve(b, depth + 1)
            if r:
                return r
        return None

    out = {}
    for node in ast.walk(tree):
        if (isinstance(node, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == "TASKS" for t in node.targets)
                and isinstance(node.value, ast.Dict)):
            for k, v in zip(node.value.keys, node.value.values):
                if isinstance(k, ast.Constant) and isinstance(v, ast.Name):
                    out[k.value] = resolve(v.id)
    return out


def cmd_verify_direction(args):
    path = rel(args.tasks_py)
    got = loss_types_from_source(path)
    ce = {t for t in TASKS if got.get(t) == "ce"}
    unknown = [t for t in TASKS if got.get(t) is None]
    print("parsed %s" % path)
    for t in TASKS:
        d = "higher-is-better (accuracy)" if t in HIGHER_IS_BETTER else "lower-is-better (MSE)"
        print("  %-12s loss_type=%-4s  ->  %s" % (t, got.get(t), d))
    ok = (ce == HIGHER_IS_BETTER) and not unknown
    if unknown:
        print("[FAIL] loss_type not resolvable for: %s" % unknown)
    if ce != HIGHER_IS_BETTER:
        print("[FAIL] source says ce=%s, table says higher-is-better=%s"
              % (sorted(ce), sorted(HIGHER_IS_BETTER)))
    print("direction table %s" % ("OK" if ok else "MISMATCH"))
    return 0 if ok else 1


# ---------------------------------------------------------------- run parsing / scoring
def window_score(records, steps, frac):
    lo = frac * float(steps or 0)
    vals = [r.get("metric") for r in records
            if isinstance(r.get("step"), (int, float)) and r["step"] >= lo]
    vals = [v for v in vals if isinstance(v, (int, float))]
    if not vals:
        return None, 0, lo
    return sum(vals) / len(vals), len(vals), lo


def read_run(path, frac):
    rec = {"path": path, "file": os.path.basename(path), "status": "ok"}
    try:
        with open(path, encoding="utf-8") as fh:
            d = json.load(fh)
    except Exception as e:                                          # noqa: BLE001
        rec.update(status="unreadable", error="%s: %s" % (type(e).__name__, e))
        return rec
    if not isinstance(d, dict):
        rec.update(status="unreadable", error="top level is not an object")
        return rec
    a = d.get("args") or {}
    records = d.get("records") or []
    rec.update(task=a.get("task"), algo=a.get("algo"), seed=a.get("seed"), lr=a.get("lr"),
               steps=a.get("steps"), tag=a.get("tag"), n_records=len(records))
    if is_tbptt(rec["algo"] or ""):
        w = a.get("tbptt_window", a.get("tbptt_k"))
        rec["window"] = int(w) if isinstance(w, (int, float)) else None
    else:
        rec["window"] = None
    if None in (rec["task"], rec["algo"], rec["seed"], rec["lr"]):
        rec.update(status="bad_args", error="args missing task/algo/seed/lr")
        return rec
    rec["seed"] = int(rec["seed"])
    rec["lrtag"] = mj.lr_tag(float(rec["lr"]))
    last = records[-1].get("metric") if records else None
    rec["last_metric"] = last if isinstance(last, (int, float)) else None
    if not records:
        rec.update(status="no_records", score=None, n_window=0)
        return rec
    s, n, lo = window_score(records, rec["steps"], frac)
    rec.update(n_window=n, window_lo=lo, score=s)
    if s is None:
        rec["status"] = "window_empty"
    elif not math.isfinite(s):
        rec["status"] = "diverged"
    return rec


def scan_dir(indir, frac, tasks=None, algos=None):
    runs, problems = [], []
    if not os.path.isdir(indir):
        return runs, problems
    for fn in sorted(os.listdir(indir)):
        if not fn.endswith(".json"):
            continue
        r = read_run(os.path.join(indir, fn), frac)
        if r["status"] in ("unreadable", "bad_args"):
            problems.append(r)
            continue
        if tasks and r["task"] not in tasks:
            continue
        if algos and r["algo"] not in algos:
            continue
        runs.append(r)
    return runs, problems


def key_of(score, higher_better):
    """Ranking key -- always "smaller is better"; unusable/diverged ranks last."""
    if score is None or not isinstance(score, (int, float)) or not math.isfinite(score):
        return math.inf
    return -score if higher_better else score


def usable(r, allow_fallback):
    if r["status"] in ("ok", "diverged"):
        return True                     # diverged is evidence: it competes and ranks last
    if r["status"] == "window_empty" and allow_fallback and r.get("last_metric") is not None:
        return True
    return False


def effective_score(r, allow_fallback):
    if r["status"] in ("ok", "diverged"):
        return r["score"]
    if r["status"] == "window_empty" and allow_fallback:
        return r.get("last_metric")
    return None


# ---------------------------------------------------------------- selection
def select(runs, stage, seeds, allow_partial, allow_fallback, tie_rtol, max_extend,
           restrict=None):
    """restrict: {(task, algo): [(lrtag, window), ...]} -- stage-2 candidate whitelist."""
    by_pair = {}
    for r in runs:
        by_pair.setdefault((r["task"], r["algo"]), {}) \
               .setdefault((r["lrtag"], r["window"]), {})[r["seed"]] = r

    def cfg_sort(key):
        lrtag, window = key
        return (_TAG2IDX.get(lrtag, 10 ** 6), -1 if window is None else window)

    pairs = []
    for task in TASKS:
        higher = task in HIGHER_IS_BETTER
        for algo in ALGOS:
            cands_raw = by_pair.get((task, algo), {})
            allowed = None
            if restrict is not None:
                allowed = {(t, None if w is None else int(w))
                           for t, w in restrict.get((task, algo), [])}
            cands = []
            for key in sorted(cands_raw, key=cfg_sort):
                lrtag, window = key
                per_seed = cands_raw[key]
                off_protocol = allowed is not None and key not in allowed
                seed_scores, flags = {}, []
                for sd in seeds:
                    r = per_seed.get(sd)
                    if r is None:
                        continue
                    if r["status"] != "ok":
                        flags.append("%s(s%s)" % (r["status"], sd))
                    if usable(r, allow_fallback):
                        seed_scores[sd] = effective_score(r, allow_fallback)
                n = len(seed_scores)
                mean = (sum(seed_scores.values()) / n) if n else None
                complete = (n == len(seeds))
                eligible = bool((complete or (allow_partial and n > 0)) and not off_protocol)
                cands.append({
                    "lrtag": lrtag, "lr": lr_of_tag(lrtag), "window": window,
                    "tag": tag_for(algo, lrtag, window),
                    "seed_scores": {str(k): v for k, v in seed_scores.items()},
                    "score": mean, "n_seeds": n, "complete": complete, "eligible": eligible,
                    "off_protocol": off_protocol, "extend_level": extend_level(lrtag),
                    "flags": flags, "extra_seeds": sorted(set(per_seed) - set(seeds)),
                    "seeds_present": sorted(per_seed),
                    "key": key_of(mean, higher) if eligible else math.inf,
                })

            ranked = sorted([c for c in cands if c["eligible"]],
                            key=lambda c: (c["key"], _TAG2IDX.get(c["lrtag"], 10 ** 6),
                                           -1 if c["window"] is None else c["window"]))
            sel = ranked[0] if ranked else None
            ties = []
            if sel is not None and math.isfinite(sel["key"]):
                kb = sel["key"]
                ties = [c["tag"] for c in ranked[1:]
                        if abs(c["key"] - kb) <= tie_rtol * max(1.0, abs(kb))]
            top = [{"lrtag": c["lrtag"], "lr": c["lr"], "window": c["window"],
                    "tag": c["tag"], "score": c["score"]} for c in ranked[:TOP_K_STAGE2]]
            pairs.append({
                "task": task, "algo": algo,
                "direction": "higher_is_better" if higher else "lower_is_better",
                "candidates": cands, "n_eligible": len(ranked),
                "selected": None if sel is None else
                            {"lrtag": sel["lrtag"], "lr": sel["lr"], "window": sel["window"],
                             "tag": sel["tag"], "score": sel["score"],
                             "extend_level": sel["extend_level"]},
                "ties_with_selected": ties, "top2": top,
                "boundary": (boundary_of(cands, sel, max_extend) if stage == 1
                             else informational_edge(sel)),
            })
    return pairs


def boundary_of(cands, sel, max_extend):
    """Stage-1 boundary rule: extend the grid one rung outwards, at most `max_extend`."""
    b = {"at": None, "reason": None, "next_lrtag": None, "next_lr": None,
         "next_level": None, "exhausted": False, "action": "none"}
    if sel is None:
        b["reason"] = "no eligible candidate yet"
        return b
    win = sel["window"]
    complete_tags = {c["lrtag"] for c in cands
                     if c["window"] == win and c["complete"] and not c["off_protocol"]}
    base_needed = {mj.lr_tag(l) for l in BASE_LRS}
    if not base_needed.issubset(complete_tags):
        b["reason"] = ("base grid incomplete for this pair%s (%d/%d LRs have both seeds)"
                       % ("" if win is None else "/window %s" % win,
                          len(complete_tags & base_needed), len(base_needed)))
        return b
    idxs = sorted(_TAG2IDX[t] for t in complete_tags if t in _TAG2IDX)
    i_sel = _TAG2IDX.get(sel["lrtag"])
    if i_sel is None:
        b["reason"] = "selected LR is off the 1-3 ladder"
        return b
    if i_sel == min(idxs):
        b["at"], direction = "lower", -1
    elif i_sel == max(idxs):
        b["at"], direction = "upper", +1
    else:
        b["reason"] = "interior optimum"
        return b
    nxt = neighbour_tag(sel["lrtag"], direction)
    lvl = extend_level(nxt) if nxt else None
    if nxt is None or lvl is None or lvl > max_extend:
        b["exhausted"] = True
        b["reason"] = ("winner at the %s edge but the extension cap (%d) is reached"
                       % (b["at"], max_extend))
        return b
    b.update(next_lrtag=nxt, next_lr=lr_of_tag(nxt), next_level=lvl, action="extend",
             reason="winner at the %s edge of the explored grid" % b["at"])
    return b


def informational_edge(sel):
    if sel is None:
        return {"at": None, "action": "none", "exhausted": False,
                "reason": "no eligible candidate yet"}
    return {"at": None, "action": "none", "exhausted": False,
            "reason": "stage-2 winner is the final LR (no further extension); "
                      "extend_level=%s" % sel.get("extend_level")}


# ---------------------------------------------------------------- missing runs
def expected_stage1(tasks, algos):
    outdir, exp = DEFAULT_DIRS[1], []
    for task in tasks:
        for algo in algos:
            for w in expected_windows(algo):
                for l in BASE_LRS:
                    lrtag = mj.lr_tag(l)
                    for sd in SEEDS_TUNE:
                        exp.append((task, algo, lrtag, w, sd,
                                    out_path(outdir, task, algo, sd, tag_for(algo, lrtag, w))))
    return exp


def missing_for_pairs(pairs, indir, stage, seeds, restrict=None):
    """Attach a per-pair `missing` list; return the flat list as well."""
    flat = []
    outdir_rel = indir if os.path.isabs(indir) else indir
    try:
        r = os.path.relpath(rel(indir), HERE).replace("\\", "/")
        if not r.startswith(".."):
            outdir_rel = r
    except ValueError:
        pass
    for e in pairs:
        task, algo = e["task"], e["algo"]
        want = []
        if stage == 1:
            for w in expected_windows(algo):
                for l in BASE_LRS:
                    want.append((mj.lr_tag(l), w))
            for c in e["candidates"]:                     # partially-present extensions
                if (c["extend_level"] or 0) > 0:
                    want.append((c["lrtag"], c["window"]))
            b = e.get("boundary") or {}
            if b.get("action") == "extend":               # the extension we are about to emit
                want.append((b["next_lrtag"], (e["selected"] or {}).get("window")))
        else:
            want = list((restrict or {}).get((task, algo), []))
            if not want:
                want = sorted({(c["lrtag"], c["window"]) for c in e["candidates"]})
        seen = {(c["lrtag"], c["window"]): c for c in e["candidates"]}
        miss = []
        for lrtag, w in sorted(set(want), key=lambda k: (_TAG2IDX.get(k[0], 10 ** 6),
                                                         -1 if k[1] is None else k[1])):
            c = seen.get((lrtag, w))
            have = set(c["seeds_present"]) if c else set()
            for sd in seeds:
                if sd in have:
                    continue
                p = out_path(outdir_rel, task, algo, sd, tag_for(algo, lrtag, w))
                miss.append({"lrtag": lrtag, "window": w, "seed": sd, "expected_out": p,
                             "extension": bool(extend_level(lrtag))})
                flat.append((task, algo, lrtag, w, sd, p))
        e["missing"] = miss
    return flat


# ---------------------------------------------------------------- reporting
def fmt(x, nd=6):
    if x is None or not isinstance(x, (int, float)):
        return "--"
    if isinstance(x, float):
        if x != x:
            return "nan"
        if not math.isfinite(x):
            return "inf" if x > 0 else "-inf"
    return ("%." + str(nd) + "g") % x


def cfg_label(c):
    return c["lrtag"] if c.get("window") is None else "%s/w%s" % (c["lrtag"], c["window"])


def write_report(pairs, problems, meta, md_path, json_path):
    d = os.path.dirname(md_path)
    if d:
        os.makedirs(d, exist_ok=True)
    stage, seeds = meta["stage"], meta["seeds"]
