def cos(a, b):
    na, nb = a.norm(), b.norm()
    if na < 1e-12 or nb < 1e-12:
        return float("nan")
    return ((a * b).sum() / (na * nb)).item()


def _nanmean(xs):
    """Mean over the finite entries; None if there are none (inf/NaN are dropped)."""
    v = [x for x in xs if x is not None and math.isfinite(x)]
    return (sum(v) / len(v)) if v else None


def _sanitize(o):
    """Replace non-finite floats by None so the json stays strict-JSON parseable."""
    if isinstance(o, float):
        return o if math.isfinite(o) else None
    if isinstance(o, dict):
        return {k: _sanitize(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_sanitize(v) for v in o]
    return o


@torch.no_grad()
def reset_tracker_lanes(a, mask):
    """Zero the estimator state of the reset lanes -- mirrors OnlineLearner._reset_lanes
    exactly, so a tracker resets in the same step and the same way as the trainer."""
    if getattr(a, "J", None) is not None:
        a.J[mask] = 0.0
    for attr in ("S", "L", "R"):
        t = getattr(a, attr, None)
        if t is not None and t.numel():
            t[mask] = 0.0
    if getattr(a, "e", None) is not None:
        a.e[mask] = 0.0
    if hasattr(a, "reset_lanes"):
        a.reset_lanes(mask)


class RngSlot:
    """A private RNG stream for one stochastic tracker.

    `with slot:` installs the slot's state as the ambient generator state, and on exit
    stores the advanced state back into the slot and restores the ambient state.  The
    trainer's stream and the other trackers' streams are therefore untouched.
    """

    def __init__(self, device, seed):
        self.cuda = torch.device(device).type == "cuda"
        self.dev = torch.device(device) if self.cuda else None
        amb = self._get()
        if self.cuda:
            with torch.cuda.device(self.dev):
                torch.cuda.manual_seed(seed)
        else:
            torch.manual_seed(seed)
        self.state = self._get()
        self._set(amb)
        self._amb = None

    def _get(self):
        return torch.cuda.get_rng_state(self.dev) if self.cuda else torch.get_rng_state()

    def _set(self, s):
        if self.cuda:
            torch.cuda.set_rng_state(s, self.dev)
        else:
            torch.set_rng_state(s)

    def __enter__(self):
        self._amb = self._get()
        self._set(self.state)
        return self

    def __exit__(self, *exc):
        self.state = self._get()
        self._set(self._amb)
        self._amb = None
        return False


class _Null:
    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False


# --------------------------------------------------------------------------------------
# D2-style online counters (same definitions as run_m3.CertCounters, kept local so this
# script never depends on run_m3 being importable / unchanged; `n_no_signal` is the
# explicit version of run_m3's implicit "ghat_norm == 0 is never counted as informative")
# --------------------------------------------------------------------------------------
class CertCounters:
    """rho^g_t = bound_t / ||ghat_t||_F  with  bound_t = mean_b ||delta_b||_2 * e_b.

    (i)  rho^g_t < 1   -> direction-certifiable without a shadow (also < 0.5)
    (ii) T_t = e_t / ||E_t||_F <= 10 -> certificate tight (needs the shadow)
    plus the Theorem-1 check ||g - ghat||_F <= bound_t and the Lemma-1 validity check
    ||E_t||_F <= e_t; both violation counters must stay at 0.
    """

    def __init__(self, has_shadow=True):
        self.has_shadow = has_shadow
        self.n_steps = 0
        self.n_no_signal = 0
        self.n_rel_lt1 = 0
        self.n_rel_lt05 = 0
        self.n_tight_checked = 0
        self.n_tight_finite = 0
        self.n_tight_inf = 0
        self.n_tight_le10 = 0
        self.n_bound_violation = 0
        self.n_bound_finite = 0
        self.n_bound_inf = 0
        self.n_rel_finite = 0
        self.n_rel_inf = 0
        self.n_cert_invalid = 0
        self.sum_rel = 0.0
        self.max_rel = 0.0
        self.sum_tight = 0.0
        self.max_tight = 0.0

    def update(self, bound, ghat_norm, gerr_norm, e_mean, trueE_mean,
               g_scale=0.0, e_scale=0.0):
        """g_scale / e_scale set the ABSOLUTE tolerance of the two validity tests.

        A tracker run at r >= n is the Corollary-3 exact path: e_t == 0 and E_t == 0
        analytically, while the measured ||g - ghat|| and ||E_t||_F are float32 round-off
        (~1e-6 of the gradient / of ||J_t||_F).  A purely relative test then reports every
        such step as a Theorem-1 / Lemma-1 violation.  The tests are therefore
            gerr  <= bound * (1 + 1e-4) + 1e-4 * g_scale
            trueE <= e_t   * (1 + 1e-4) + 1e-4 * e_scale
        with g_scale = max(||g||, ||ghat||) and e_scale = ||J_t||_F."""
        self.n_steps += 1
        if ghat_norm > EPS:
            rel = bound / ghat_norm
            # Without spectral clipping the certificate recursion e_t = rho_bar e_{t-1}
            # + eta_t has rho_bar ~ ||A||_F >> 1, so e_t saturates float32 within a few
            # tens of steps and rho^g_t is +inf.  Such steps are NOT informative; they
            # are counted separately so every mean below stays finite.
            if math.isfinite(rel):
                self.n_rel_finite += 1
                self.sum_rel += rel
                self.max_rel = max(self.max_rel, rel)
                if rel < 1.0:
                    self.n_rel_lt1 += 1
                if rel < 0.5:
                    self.n_rel_lt05 += 1
            else:
                self.n_rel_inf += 1
        else:
            self.n_no_signal += 1
        if gerr_norm is not None:
            if math.isfinite(bound):
                self.n_bound_finite += 1
                if gerr_norm > bound * (1.0 + 1e-4) + 1e-4 * g_scale:
                    self.n_bound_violation += 1
            else:
                self.n_bound_inf += 1
        if trueE_mean is not None:
            if (math.isfinite(e_mean)
                    and trueE_mean > e_mean * (1.0 + 1e-4) + 1e-4 * e_scale):
                self.n_cert_invalid += 1
            if trueE_mean > 1e-12:
                tight = e_mean / trueE_mean
                self.n_tight_checked += 1
                if math.isfinite(tight):
                    self.n_tight_finite += 1
                    self.sum_tight += tight
                    self.max_tight = max(self.max_tight, tight)
                else:
                    self.n_tight_inf += 1
                if tight <= 10.0:
                    self.n_tight_le10 += 1

    def summary(self):
        ns = max(self.n_steps, 1)
        nsig = max(self.n_steps - self.n_no_signal, 1)
        nt = max(self.n_tight_checked, 1)
        # frac_tight_le10 is over every checked step: an overflowed e_t is
        # a loose certificate, not a missing measurement.
        return {
            "n_steps": self.n_steps,
            "n_no_signal": self.n_no_signal,
            "n_rel_lt1": self.n_rel_lt1,
            "n_rel_lt05": self.n_rel_lt05,
            "n_tight_checked": self.n_tight_checked,
            "n_tight_finite": self.n_tight_finite,
            "n_tight_inf": self.n_tight_inf,
            "n_tight_le10": self.n_tight_le10,
            "n_bound_violation": self.n_bound_violation,
            "n_bound_finite": self.n_bound_finite,
            "n_bound_inf": self.n_bound_inf,
            "n_rel_finite": self.n_rel_finite,
            "n_rel_inf": self.n_rel_inf,
            "n_cert_invalid": self.n_cert_invalid,
            # over ALL counted steps (no-signal steps count against informativeness)
            "frac_rel_lt1": self.n_rel_lt1 / ns,
            "frac_rel_lt05": self.n_rel_lt05 / ns,
            # over the steps that carried a gradient signal
            "frac_rel_lt1_signal": self.n_rel_lt1 / nsig,
            "frac_rel_lt05_signal": self.n_rel_lt05 / nsig,
            "frac_tight_le10": (self.n_tight_le10 / nt) if self.n_tight_checked else None,
            "mean_rel_g": ((self.sum_rel / self.n_rel_finite)
                           if self.n_rel_finite else None),
            "max_rel_g": self.max_rel,
            "mean_tightness": ((self.sum_tight / self.n_tight_finite)
                               if self.n_tight_finite else None),
            "max_tightness": self.max_tight if self.n_tight_finite else None,
            "has_shadow": self.has_shadow,
            "cert_overflow_note": "n_rel_inf / n_bound_inf / n_tight_inf count steps "
                                  "whose certificate e_t had already overflowed float32 "
                                  "(rho_bar > 1 with no spectral clip); never counted as "
                                  "certifiable or tight",
            "violation_tol": "gerr <= bound*(1+1e-4) + 1e-4*max(||g||,||ghat||); "
                             "trueE <= e_t*(1+1e-4) + 1e-4*||J_t||_F",
            "delta_agg": "mean_b(||delta_b||_2 * e_b)",
            "counted_steps": "labelled steps with step >= cert_warmup and age >= "
                             "cert_min_age, stride cert_every",
        }


