"""D4 (fair baseline protocol) learning-rate selection and follow-up job generation.

Implements the selection half of R2_EXPERIMENT_PLAN.md D4 + section 4 ("Adopted / D4").
Stage-1 jobs themselves are generated by `make_r2_jobs.py --stage d4_tune`; this script
never re-implements the job-line format -- it imports `make_r2_jobs` and calls
`m3_job` / `lr_tag`, so the emitted lines and the `# out=` annotations stay identical
to package A's by construction.

Protocol implemented here
-------------------------
score(run)        mean of `records[*].metric` over the last 20 % of the run, i.e. every
                  logged record with  step >= 0.8 * args.steps  (`--frac` to change).
                  args.steps is read per run, so the 6 000-step screen and the
                  20 000-step stage-2 runs each use their own window.
score(config)     unweighted mean of the two per-seed scores -- the seed is the unit of
                  aggregation, never the pooled record set.
direction         run_m3.py logs `metric` = accuracy for the cross-entropy tasks
                  (copy, anbn) and the MSE value for every other D4 task, so the former
                  are maximised and the latter minimised (see `verify-direction`).
eligibility       a config competes only when every tuning seed produced a usable score;
                  a non-finite window mean (divergence) ranks last.
ties              broken towards the smaller learning rate, then the smaller TBPTT
                  window; every tie is reported.
boundary          if the winner sits at the edge of the explored LR set (and the whole
                  base grid is complete for that pair) the grid is extended one rung
                  outwards on the 1-3 ladder, at most twice (`--max-extend`).
stage 2           the top-2 configs per (task, algo) are re-run at 20 000 steps with the
                  same tuning seeds; the winner there is the final LR.
evaluation        final LR x seeds 0-9 x 20 000 steps, shadow on.

Sub-commands
------------
  select --stage 1        read <indir> (default results/r2/d4_tune)   -> D4_SELECT_stage1.{md,json}
  select --stage 2        read <indir> (default results/r2/d4_stage2) -> D4_SELECT_stage2.{md,json}
  emit --what boundary    -> jobs/d4_boundary.txt  (stage-1 supplements: LR extension + TBPTT window fill)
  emit --what stage2      -> jobs/d4_stage2.txt
  emit --what eval        -> jobs/d4_eval.txt
  status                  completion / missing counts per stage
  verify-direction        cross-check the metric-direction table against skrtrl/tasks.py

Relative paths are resolved against this script's directory (code/), exactly like
run_r2_queue.ps1 does, so the same string works from anywhere.

This script never launches anything.
"""
