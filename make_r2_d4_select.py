                row += [fmt(c["seed_scores"].get(str(s))) for s in seeds]
                row.append("**%s**" % fmt(c["score"]) if c["eligible"] else fmt(c["score"]))
                row.append("%d/%d" % (c["n_seeds"], len(seeds)))
                row.append(str(rank_of.get(id(c), "--")))
                fl = list(c["flags"])
