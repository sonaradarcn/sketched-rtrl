    e = sub.add_parser("emit", help="write a job file from a selection report")
    e.add_argument("--what", required=True, choices=["boundary", "stage2", "eval"])
    e.add_argument("--outdir", default=REPORT_DIR, help="where the selection json lives")
    e.add_argument("--sel-json", default=None, help="explicit selection json")
    e.add_argument("--out", default=None, help="explicit job-file path")
