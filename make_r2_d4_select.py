def _restrict_from_stage1(path):
    """{(task, algo): [(lrtag, window), ...]} = the top-2 chosen at stage 1."""
    if not os.path.exists(path):
        return None
    d = json.load(open(path, encoding="utf-8"))
    out = {}
    for e in d.get("pairs", []):
        top = [(c["lrtag"], c["window"]) for c in e.get("top2", [])]
        if top:
            out[(e["task"], e["algo"])] = top
    return out or None


def cmd_select(args):
    stage = args.stage
    indir = rel(args.indir or DEFAULT_DIRS[stage])
    tasks = [t for t in TASKS if not args.tasks or t in args.tasks.split(",")]
    algos = [a for a in ALGOS if not args.algos or a in args.algos.split(",")]
    runs, problems = scan_dir(indir, args.frac, set(tasks), set(algos))

    restrict = None
    if stage == 2 and not args.no_restrict:
        restrict = _restrict_from_stage1(os.path.join(rel(args.outdir),
                                                      "D4_SELECT_stage1.json"))
        if restrict is None:
            print("[warn] no D4_SELECT_stage1.json in %s -- stage-2 candidates are taken "
                  "from the directory as-is and the missing list is best-effort"
                  % rel(args.outdir), file=sys.stderr)

    pairs_all = select(runs, stage, SEEDS_TUNE, args.allow_partial,
                       args.allow_window_fallback, args.tie_rtol, args.max_extend, restrict)
    pairs = [p for p in pairs_all if p["task"] in tasks and p["algo"] in algos]
    missing_for_pairs(pairs, args.indir or DEFAULT_DIRS[stage], stage, SEEDS_TUNE, restrict)

    meta = {"stage": stage, "indir": indir.replace("\\", "/"),
            "generated": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "frac": args.frac, "seeds": SEEDS_TUNE,
            "steps_expected": STEPS_TUNE if stage == 1 else STEPS_STAGE2,
            "tie_rtol": args.tie_rtol, "max_extend": args.max_extend,
            "allow_partial": bool(args.allow_partial),
            "allow_window_fallback": bool(args.allow_window_fallback),
            "higher_is_better": sorted(HIGHER_IS_BETTER), "base_lrs": BASE_LRS,
            "tbptt_windows": TBPTT_WINDOWS, "window_flag": WINDOW_FLAG,
            "tbptt_default_window": TBPTT_DEFAULT_WINDOW,
            "tasks": tasks, "algos": algos,
            "n_runs": len(runs), "n_pairs": len(pairs),
            "restricted_to_stage1_top2": bool(restrict)}
    outdir = rel(args.outdir)
    md = os.path.join(outdir, "D4_SELECT_stage%d.md" % stage)
    js = os.path.join(outdir, "D4_SELECT_stage%d.json" % stage)
    write_report(pairs, problems, meta, md, js)

    n_sel = sum(1 for p in pairs if p["selected"])
    n_ext = sum(1 for p in pairs if (p.get("boundary") or {}).get("action") == "extend")
    n_miss = sum(len(p.get("missing", [])) for p in pairs)
    print("stage %d: %d runs parsed from %s" % (stage, len(runs), meta["indir"]))
    print("  pairs %d | selected %d | pending %d | boundary-extend %d | missing runs %d"
          % (len(pairs), n_sel, len(pairs) - n_sel, n_ext, n_miss))
    if problems:
        print("  unreadable/malformed files: %d (%s)"
              % (len(problems), ", ".join(p["file"] for p in problems[:4])))
    print("wrote %s" % md)
    print("wrote %s" % js)
    return 0


def cmd_emit(args):
    what = args.what
    stage_json = args.sel_json or os.path.join(args.outdir, "D4_SELECT_stage%d.json"
                                               % (2 if what == "eval" else 1))
    stage_json = rel(stage_json)
    if not os.path.exists(stage_json):
        raise SystemExit("%s not found -- run `select --stage %d` first"
                         % (stage_json, 2 if what == "eval" else 1))
    d = json.load(open(stage_json, encoding="utf-8"))
    pairs = {(e["task"], e["algo"]): e for e in d.get("pairs", [])}
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    src = os.path.basename(stage_json)
    head, notes, body = [], [], []

    if what == "boundary":
        outdir = DEFAULT_DIRS[1]
        head += ["# D4 stage-1 supplements, generated %s from %s" % (stamp, src),
                 "# LR-grid extensions (one rung on the 1-3 ladder, cap %d) plus the TBPTT "
                 "window fill; %d steps, tuning seeds %s, shadow on, svd_driver auto"
                 % (args.max_extend, STEPS_TUNE, SEEDS_TUNE),
                 "# written to the same directory as the screen (%s), so `select --stage 1` "
                 "picks them up automatically" % outdir]
        plan = {}          # (task, algo) -> [(lrtag, window, why)]
        for (task, algo), e in pairs.items():
            b = e.get("boundary") or {}
            if b.get("action") == "extend" and b.get("next_lrtag"):
                plan.setdefault((task, algo), []).append(
                    (b["next_lrtag"], (e.get("selected") or {}).get("window"), "boundary"))
        if not args.no_tbptt_fill:
            for task in TASKS:
                for algo in ALGOS:
                    if not is_tbptt(algo):
                        continue
                    e = pairs.get((task, algo)) or {}
                    have = {(c["lrtag"], c["window"]) for c in e.get("candidates", [])
                            if c.get("complete")}
                    for w in TBPTT_WINDOWS:
                        if w == TBPTT_DEFAULT_WINDOW:
                            continue
                        for l in BASE_LRS:
                            t = mj.lr_tag(l)
                            if (t, w) not in have:
                                plan.setdefault((task, algo), []).append((t, w, "window-fill"))
        n_b = sum(1 for v in plan.values() for c in v if c[2] == "boundary")
        n_w = sum(1 for v in plan.values() for c in v if c[2] == "window-fill")
        notes.append("# %d LR-extension config(s), %d TBPTT window-fill config(s), "
                     "x %d seeds" % (n_b, n_w, len(SEEDS_TUNE)))
        for task in TASKS:
            for seed in SEEDS_TUNE:
                for algo in ALGOS:
                    for lrtag, w, _why in plan.get((task, algo), []):
                        body.append(job_line(task, algo, seed, lrtag, w, STEPS_TUNE, outdir))

    elif what == "stage2":
        outdir = DEFAULT_DIRS[2]
        head += ["# D4 stage-2 tuning, generated %s from %s" % (stamp, src),
                 "# top-%d stage-1 LRs per (task, estimator) x seeds %s x %d steps, "
                 "shadow on, svd_driver auto" % (TOP_K_STAGE2, SEEDS_TUNE, STEPS_STAGE2),
                 "# final LR = best last-20%% window mean here (mean over the two seeds)"]
        skipped = set()
        for task in TASKS:
            for rank in range(TOP_K_STAGE2):
                for seed in SEEDS_TUNE:
                    for algo in ALGOS:
                        e = pairs.get((task, algo))
                        if not e:
                            continue
                        b = e.get("boundary") or {}
                        if b.get("action") == "extend" and not args.include_pending:
                            skipped.add("%s/%s" % (task, algo))
                            continue
                        top = e.get("top2") or []
                        if rank >= len(top):
                            continue
                        c = top[rank]
                        body.append(job_line(task, algo, seed, c["lrtag"], c["window"],
                                             STEPS_STAGE2, outdir))
        if skipped:
            notes.append("# withheld because a boundary extension is still pending "
                         "(re-run select+emit after the supplements land; --include-pending "
                         "overrides): %s" % ", ".join(sorted(skipped)))

    else:                                                                     # eval
        outdir = EVAL_DIR
        head += ["# D4 evaluation, generated %s from %s" % (stamp, src),
                 "# final LR per (task, estimator) x seeds %d-%d x %d steps, shadow on, "
                 "svd_driver auto" % (SEEDS_EVAL[0], SEEDS_EVAL[-1], STEPS_EVAL)]
        pend = set()
        for task in TASKS:
            for seed in SEEDS_EVAL:
                for algo in ALGOS:
                    e = pairs.get((task, algo))
                    if not e or not e.get("selected"):
                        pend.add("%s/%s" % (task, algo))
                        continue
                    s = e["selected"]
                    body.append(job_line(task, algo, seed, s["lrtag"], s["window"],
                                         STEPS_EVAL, outdir))
        if pend:
            notes.append("# no stage-2 winner yet, not emitted: %s" % ", ".join(sorted(pend)))

    out = rel(args.out or os.path.join(JOBS_DIR, JOB_FILES[what]))
    d_out = os.path.dirname(out)
    if d_out:
        os.makedirs(d_out, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(head + notes + body) + "\n")
    done = sum(1 for l in body if _out_of(l) and os.path.exists(rel(_out_of(l))))
    print("wrote %s: %d jobs (%d already have output -> the queue exists-skips them)"
          % (out, len(body), done))
    for n in notes:
        print("  " + n.lstrip("# "))
    return 0


_OUT_RE = re.compile(r"#\s*out\s*=\s*(\S+)\s*$")


def _out_of(line):
    m = _OUT_RE.search(line)
    return m.group(1) if m else None


def cmd_status(args):
    print("D4 status (relative paths are under %s)" % HERE)
    exp1 = expected_stage1(TASKS, ALGOS)
    have = sum(1 for row in exp1 if os.path.exists(rel(row[-1])))
    print("\n[stage 1 base grid]  %s" % DEFAULT_DIRS[1])
    print("  expected %d runs = %d tasks x %d algos x %d LRs x %d seeds "
          "(TBPTT counted over %d windows %s)"
          % (len(exp1), len(TASKS), len(ALGOS), len(BASE_LRS), len(SEEDS_TUNE),
             len(TBPTT_WINDOWS), TBPTT_WINDOWS))
    print("  present  %d   missing %d" % (have, len(exp1) - have))
    runs, problems = scan_dir(rel(DEFAULT_DIRS[1]), args.frac)
    ext = [r for r in runs if (extend_level(r["lrtag"]) or 0) > 0]
    print("  json parsed %d (LR-extension runs %d, unreadable/malformed %d)"
          % (len(runs), len(ext), len(problems)))
    bad = [r for r in runs if r["status"] != "ok"]
    if bad:
        print("  runs without a usable last-%d%% window: %d"
              % (round((1.0 - args.frac) * 100), len(bad)))
        for r in bad[:args.list_limit]:
            print("    %-54s %-13s records %-3s steps %s"
                  % (r["file"], r["status"], r["n_records"], r["steps"]))
        if len(bad) > args.list_limit:
            print("    ... %d more" % (len(bad) - args.list_limit))

    for label, sub in (("stage 2", DEFAULT_DIRS[2]), ("evaluation", EVAL_DIR)):
        p = rel(sub)
        rr, pp = scan_dir(p, args.frac)
        print("\n[%s]  %s%s" % (label, sub, "" if os.path.isdir(p) else "   [directory absent]"))
        print("  json parsed %d (unreadable/malformed %d)" % (len(rr), len(pp)))

    print("\n[job files]")
    for fn in ["d4_tune.txt"] + [JOB_FILES[k] for k in ("boundary", "stage2", "eval")]:
        p = rel(os.path.join(JOBS_DIR, fn))
        if not os.path.exists(p):
            print("  %-18s (absent)" % fn)
            continue
        n = ndone = nun = 0
        with open(p, encoding="utf-8") as fh:
            for line in fh:
                t = line.strip()
                if not t or t.startswith("#"):
                    continue
                n += 1
                o = _out_of(t)
                if o is None:
                    nun += 1
                elif os.path.exists(rel(o)):
                    ndone += 1
        print("  %-18s %4d jobs | done %4d | todo %4d%s"
              % (fn, n, ndone, n - ndone, "" if not nun else
                 " | %d line(s) without # out=" % nun))
    return 0


